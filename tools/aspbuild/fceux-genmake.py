"""Generate a plain Makefile for FCEUX's SDL build.

FCEUX 2.2.3 ships SCons scripts written for Python 2 and SCons 1.x; on a
modern SCons they fail in three different ways in a row (print statements,
dict.has_key, then a CheckLib signature change). The source lists themselves
are trivial - globs plus a couple of explicit Split() blocks - so this reads
them and emits a Makefile instead of fighting the build system.
"""
import glob
import os
import re

SRC = '/home/claude/aspwork/src/fceux/trunk/src'


def split_block(path, var='source_list'):
    """Pull the file names out of a Split(\"\"\" ... \"\"\") block."""
    text = open(path).read()
    m = re.search(r'Split\(\s*"""(.*?)"""', text, re.S)
    if not m:
        return []
    return [w for w in m.group(1).split() if w.endswith(('.c', '.cpp'))]


def globbed(subdir, exts=('*.cpp', '*.c')):
    out = []
    for e in exts:
        out += [os.path.relpath(p, SRC)
                for p in glob.glob(os.path.join(SRC, subdir, e))]
    return out


sources = []
# src/*.cpp, minus the Lua engine (LUA=0)
sources += [os.path.relpath(p, SRC) for p in glob.glob(os.path.join(SRC, '*.cpp'))
            if os.path.basename(p) != 'lua-engine.cpp']
sources += globbed('boards')
sources += globbed('drivers/common')
sources += globbed('input')
# utils and drivers/sdl use explicit lists
sources += ['utils/' + f for f in split_block(os.path.join(SRC, 'utils/SConscript'))]
sources += ['drivers/sdl/' + f
            for f in split_block(os.path.join(SRC, 'drivers/sdl/SConscript'))]

# things excluded by the options we build with (no GTK, no OpenGL, no AVI,
# no Lua, no netplay GUI)
# unix-netplay.cpp defines the FCEUD_Net* callbacks the core references,
# and utils/{unzip,ioapi}.cpp are the bundled minizip the file loader needs;
# the upstream Split() list omits them because SCons picked them up by glob.
sources += ['drivers/sdl/unix-netplay.cpp', 'utils/unzip.cpp', 'utils/ioapi.cpp']
drop = ('drivers/sdl/sdl-video-gtk', 'drivers/sdl/gui.cpp',
        'drivers/sdl/sdl-opengl', 'utils/backward.cpp')
sources = sorted({s for s in sources if not s.startswith(drop)})

missing = [s for s in sources if not os.path.exists(os.path.join(SRC, s))]
if missing:
    print('WARNING: listed but absent:', missing)
    sources = [s for s in sources if s not in missing]

SYSROOT = '/home/claude/md/sysroot'
DEFINES = ['PSS_STYLE=1', 'LSB_FIRST', 'FRAMESKIP', 'PUBLIC_RELEASE', 'ASP_BUILD']

mk = f"""# generated by genmake.py - do not hand-edit
CXX = arm-linux-gnueabi-g++
CC  = arm-linux-gnueabi-gcc
SYSROOT = {SYSROOT}
DEFS = {' '.join('-D' + d for d in DEFINES)}
INC  = -I. -I./drivers -I./drivers/common -I$(SYSROOT)/include \\
       -I$(SYSROOT)/include/SDL
OPT  = -O2 -march=armv5te -ffast-math -fomit-frame-pointer -w
CXXFLAGS = $(OPT) $(DEFS) $(INC) -fpermissive
CFLAGS   = $(OPT) $(DEFS) $(INC)
LDFLAGS  = -static -L$(SYSROOT)/lib
LDLIBS   = -lSDL -lz -lm -lpthread -ldl

OBJS = \\
"""
mk += ' \\\n'.join('\t' + re.sub(r'\.(cpp|c)$', '.o', s) for s in sources)
mk += """

all: fceux.dge

fceux.dge: $(OBJS)
\t$(CXX) -o $@ $(OBJS) $(LDFLAGS) $(LDLIBS)

%.o: %.cpp
\t$(CXX) -c $(CXXFLAGS) $< -o $@

%.o: %.c
\t$(CC) -c $(CFLAGS) $< -o $@

clean:
\trm -f $(OBJS) fceux.dge
"""

open(os.path.join(SRC, 'Makefile.asp'), 'w').write(mk)
print(f'{len(sources)} source files -> {SRC}/Makefile.asp')
